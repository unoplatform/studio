<#
.SYNOPSIS
Regenerates the THEMEKEY (UNOL202) catalogs: the resource keys each theme's control styles define or read, for the
control families in controls.txt.

.DESCRIPTION
Downloads each package from nuget.org, reads the string literals of its theme assembly (Uno compiles XAML to C#, so
every key a style defines or looks up is a literal there) and keeps those that start with a control family name
followed by an upper-case letter. A literal that is not a key only makes a catalog larger, so the rule reports less,
never more. Run it when a theme package version moves; the versions used are written at the top of each file.
#>
param(
    [string] $WinUIVersion = '7.0.65',
    [string] $ThemesVersion = '9.0.1',
    [string] $Out = (Join-Path $PSScriptRoot '..\src\Uno.Lint.Core\ThemeKeys')
)
$ErrorActionPreference = 'Stop'

$controls = Get-Content (Join-Path $PSScriptRoot 'controls.txt') | Where-Object { $_ -and -not $_.StartsWith('#') }
$family = [regex]('^(?:' + (($controls | Sort-Object Length -Descending) -join '|') + ')[A-Z]')

$catalogs = @(
    @{ Name = 'fluent'; Id = 'uno.winui'; Version = $WinUIVersion; Dll = 'Uno.UI.FluentTheme.dll' }
    @{ Name = 'simple'; Id = 'uno.simple.winui'; Version = $ThemesVersion; Dll = 'Uno.Simple.WinUI.dll' }
    @{ Name = 'material'; Id = 'uno.material.winui'; Version = $ThemesVersion; Dll = 'Uno.Material.WinUI.dll' }
    @{ Name = 'cupertino'; Id = 'uno.cupertino.winui'; Version = $ThemesVersion; Dll = 'Uno.Cupertino.WinUI.dll' }
)

$work = Join-Path ([IO.Path]::GetTempPath()) "uno-lint-themekeys-$PID"
New-Item -ItemType Directory -Force $work, $Out | Out-Null
try {
    foreach ($c in $catalogs) {
        $nupkg = Join-Path $work "$($c.Id).$($c.Version).nupkg"
        Invoke-WebRequest "https://api.nuget.org/v3-flatcontainer/$($c.Id)/$($c.Version)/$($c.Id).$($c.Version).nupkg" -OutFile $nupkg
        $dir = Join-Path $work $c.Name
        Expand-Archive $nupkg $dir -Force
        # The plain .NET build (lib/netX.Y), not a platform head.
        $dll = Get-ChildItem $dir -Recurse -Filter $c.Dll | Where-Object { $_.Directory.Name -match '^net\d+\.\d+$' } |
            Sort-Object { [version]($_.Directory.Name -replace '^net') } | Select-Object -Last 1
        if (-not $dll) { throw "$($c.Dll) not found in $($c.Id) $($c.Version)" }

        # User strings are UTF-16; read at both byte alignments.
        $bytes = [IO.File]::ReadAllBytes($dll.FullName)
        $keys = foreach ($offset in 0, 1) {
            $text = [Text.Encoding]::Unicode.GetString($bytes, $offset, $bytes.Length - $offset)
            # Style and template names (ListViewItemStyle) are not lightweight-styling keys.
            [regex]::Matches($text, '[A-Z][A-Za-z0-9]{3,120}') | ForEach-Object Value |
                Where-Object { $family.IsMatch($_) -and $_ -notmatch '(Style|Template)$' }
        }
        $keys = $keys | Sort-Object -Unique -CaseSensitive
        $header = "# $($c.Id) $($c.Version), $($dll.Directory.Name)/$($c.Dll); generated by catalog/Update-ThemeKeys.ps1"
        Set-Content -Path (Join-Path $Out "$($c.Name).txt") -Value (@($header) + $keys) -Encoding utf8NoBOM
        "{0,-10} {1,5} keys  ({2} {3})" -f $c.Name, $keys.Count, $c.Id, $c.Version
    }
}
finally {
    Remove-Item $work -Recurse -Force -ErrorAction SilentlyContinue
}
